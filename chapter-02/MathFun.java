public class MathFun {
    public static void main(String[] args) {
        // Use Math methods to do basic calculations.
        double squareRoot = Math.sqrt(64);
        System.out.println(squareRoot);
        System.out.println(Math.ceil(12.5));

        // Raise 2 to the 8th power.
        double powersThatBe = Math.pow(2, 8);
        System.out.println(powersThatBe);
    }
}
